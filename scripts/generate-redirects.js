#!/usr/bin/env node
/**
 * Generate 301 redirects for old business slugs.
 * 
 * Old-style slugs (e.g., /business/superior-service-hvac-overland-park) need to
 * 301 redirect to canonical slugs (e.g., /business/superior-service).
 * 
 * This script queries Supabase for all business_cities rows where slug != canonical_slug
 * and generates a next.config.ts with static 301 redirects.
 * 
 * Usage: node scripts/generate-redirects.js
 * 
 * After running, review next.config.ts and deploy.
 */

const { createClient } = require("@supabase/supabase-js");

const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL;
const supabaseKey = process.env.SUPABASE_SERVICE_ROLE_KEY;

if (!supabaseUrl || !supabaseKey) {
  // Try reading from creds file
  const fs = require("fs");
  const path = require("path");
  const credsPath = path.join(__dirname, "..", "supabase_creds.txt");
  if (fs.existsSync(credsPath)) {
    const creds = fs.readFileSync(credsPath, "utf8");
    const urlMatch = creds.match(/project_url=(.+)/);
    const keyMatch = creds.match(/service_role_key=(.+)/);
    if (urlMatch) process.env.NEXT_PUBLIC_SUPABASE_URL = urlMatch[1].replace("/rest/v1/", "");
    if (keyMatch) process.env.SUPABASE_SERVICE_ROLE_KEY = keyMatch[1];
  }
}

const client = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL,
  process.env.SUPABASE_SERVICE_ROLE_KEY
);

async function main() {
  const { data, error } = await client
    .from("business_cities")
    .select("slug, canonical_slug")
    .neq("slug", "");  // Get all rows

  if (error) {
    console.error("Error fetching slugs:", error);
    process.exit(1);
  }

  // Filter to only rows where slug != canonical_slug (old-style slugs)
  const redirects = data.filter(row => row.slug !== row.canonical_slug);

  console.log(`Found ${redirects.length} old-style slugs needing 301 redirects.`);

  // Generate next.config.ts
  const header = `import type { NextConfig } from "next";

const nextConfig: NextConfig = {
  async redirects() {
    // Static 301 redirects for old business slugs (category-city suffix format).
    // Previously handled at runtime with permanentRedirect() which returns 308.
    // Google handles 301 more reliably for permanent redirects.
    // Edge-level redirects are also faster (no database query needed).
    //
    // GENERATED BY: node scripts/generate-redirects.js
    // LAST UPDATED: ${new Date().toISOString().split("T")[0]}
    return [`;

  const entries = redirects.map(row =>
    `  { source: '/business/${row.slug}', destination: '/business/${row.canonical_slug}', permanent: true },`
  );

  const footer = `    ];
  },
};

export default nextConfig;`;

  const fs = require("fs");
  const path = require("path");
  const configPath = path.join(__dirname, "..", "next.config.ts");
  
  fs.writeFileSync(configPath, header + "\n" + entries.join("\n") + "\n" + footer);
  console.log(`Wrote ${redirects.length} redirects to ${configPath}`);
}

main().catch(console.error);